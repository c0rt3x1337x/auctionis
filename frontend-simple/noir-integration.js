/**
 * Noir ZK Proof Integration for Sealed-Bid Auction
 *
 * This module handles the generation of zero-knowledge proofs using the Noir circuit.
 * It requires the compiled circuit artifacts from: circuits/bid_proof/target/
 */

import { BarretenbergBackend } from '@noir-lang/backend_barretenberg';
import { Noir } from '@noir-lang/noir_js';

// This will be loaded from the compiled circuit
let noir = null;
let backend = null;

/**
 * Initialize the Noir circuit
 * Must be called before generating proofs
 */
export async function initializeCircuit() {
    try {
        // Load the compiled circuit
        const circuitResponse = await fetch('./circuit/bid_proof.json');
        const circuit = await circuitResponse.json();

        // Initialize backend and Noir instance
        backend = new BarretenbergBackend(circuit);
        noir = new Noir(circuit, backend);

        console.log('Noir circuit initialized successfully');
        return true;
    } catch (error) {
        console.error('Failed to initialize Noir circuit:', error);
        throw new Error('Circuit initialization failed. Make sure bid_proof.json is in the circuit/ directory.');
    }
}

/**
 * Generate a ZK proof for a bid
 *
 * @param {bigint} bidAmount - The bid amount (1 to 2^32-1)
 * @param {bigint} secret - Random secret for commitment
 * @param {string} bidderAddress - Ethereum address of the bidder
 * @returns {Promise<{proof: Uint8Array, publicInputs: object, commitment: string}>}
 */
export async function generateBidProof(bidAmount, secret, bidderAddress) {
    if (!noir || !backend) {
        await initializeCircuit();
    }

    // Validate inputs
    const MAX_BID_AMOUNT = 4294967295n; // 2^32 - 1
    const MIN_BID_AMOUNT = 1n;

    if (bidAmount < MIN_BID_AMOUNT || bidAmount > MAX_BID_AMOUNT) {
        throw new Error(`Bid amount must be between ${MIN_BID_AMOUNT} and ${MAX_BID_AMOUNT}`);
    }

    if (typeof secret === 'string') {
        secret = BigInt(secret);
    }

    if (secret === 0n) {
        throw new Error('Secret cannot be zero');
    }

    // Convert address to field element
    let addressField;
    if (typeof bidderAddress === 'string') {
        addressField = BigInt(bidderAddress);
    } else {
        addressField = bidderAddress;
    }

    // Calculate commitment using Poseidon hash (this happens inside the circuit)
    // We need to provide it as a public input
    const commitment = await calculateCommitment(bidAmount, secret, addressField);

    // Prepare circuit inputs
    const inputs = {
        bid_amount: bidAmount.toString(),
        secret: secret.toString(),
        bidder_address: addressField.toString(),
        commitment: commitment.toString()
    };

    console.log('Generating proof with inputs:', inputs);

    try {
        // Generate the proof
        const { witness } = await noir.execute(inputs);
        const proof = await backend.generateProof(witness);

        console.log('Proof generated successfully');
        console.log('Proof size:', proof.proof.length, 'bytes');

        return {
            proof: proof.proof,
            publicInputs: proof.publicInputs,
            commitment: '0x' + commitment.toString(16).padStart(64, '0')
        };
    } catch (error) {
        console.error('Proof generation failed:', error);
        throw new Error('Failed to generate ZK proof: ' + error.message);
    }
}

/**
 * Calculate Poseidon commitment
 * NOTE: This is a simplified version. The actual commitment is calculated inside the Noir circuit.
 * For the public input, we can use keccak256 as a placeholder until Poseidon is available in JS.
 *
 * @param {bigint} bidAmount
 * @param {bigint} secret
 * @param {bigint} bidderAddress
 * @returns {Promise<bigint>}
 */
async function calculateCommitment(bidAmount, secret, bidderAddress) {
    // IMPORTANT: This should use Poseidon hash to match the circuit
    // For now, we'll use a placeholder that works with the circuit's output
    // The circuit will calculate the real Poseidon commitment

    // The commitment will be generated by the circuit, but we need to provide
    // a value here. In practice, you'd use a JS Poseidon library like:
    // import { buildPoseidon } from 'circomlibjs';
    // const poseidon = await buildPoseidon();
    // return poseidon.F.toObject(poseidon([bidAmount, secret, bidderAddress]));

    // For now, using keccak256 as a temporary placeholder
    // YOU MUST REPLACE THIS with actual Poseidon hash for production
    const encoder = new TextEncoder();
    const data = `${bidAmount}-${secret}-${bidderAddress}`;
    const hashBuffer = await crypto.subtle.digest('SHA-256', encoder.encode(data));
    const hashArray = new Uint8Array(hashBuffer);

    let hash = 0n;
    for (let i = 0; i < 32; i++) {
        hash = (hash << 8n) | BigInt(hashArray[i]);
    }

    return hash;
}

/**
 * Verify a proof (for testing purposes)
 *
 * @param {Uint8Array} proof
 * @param {object} publicInputs
 * @returns {Promise<boolean>}
 */
export async function verifyProof(proof, publicInputs) {
    if (!backend) {
        await initializeCircuit();
    }

    try {
        const verified = await backend.verifyProof({ proof, publicInputs });
        console.log('Proof verification result:', verified);
        return verified;
    } catch (error) {
        console.error('Proof verification failed:', error);
        return false;
    }
}

/**
 * Generate a cryptographically secure random secret
 *
 * @returns {bigint}
 */
export function generateRandomSecret() {
    const randomBytes = new Uint8Array(32);
    crypto.getRandomValues(randomBytes);

    let secret = 0n;
    for (let i = 0; i < 32; i++) {
        secret = (secret << 8n) | BigInt(randomBytes[i]);
    }

    // Ensure it's not zero
    if (secret === 0n) {
        secret = 1n;
    }

    return secret;
}

/**
 * Format proof for Solidity contract
 *
 * @param {Uint8Array} proof
 * @returns {string} Hex string with 0x prefix
 */
export function formatProofForContract(proof) {
    return '0x' + Array.from(proof)
        .map(b => b.toString(16).padStart(2, '0'))
        .join('');
}
